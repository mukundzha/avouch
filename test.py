def short_chain(x):
    if x == 1:
        return "one"
    elif x == 2:
        return "two"
    else:
        return "other"


def long_chain(x):
    if x == 1:
        return "one"
    elif x == 2:
        return "two"
    elif x == 3:
        return "three"
    elif x == 4:
        return "four"
    elif x == 5:
        return "five"
    elif x == 6:
        return "six"
    else:
        return "other"